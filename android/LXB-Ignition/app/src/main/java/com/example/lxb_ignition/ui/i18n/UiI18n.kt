// Batch 6: language infrastructure moved verbatim from MainActivity.kt.
// The mechanism is unchanged: UiI18n maps English source text through ZhMap
// for zh and passes text through for any other language. This is NOT Android
// stringResource: uiLang is user-settable in Config and differs from the
// system locale, so a stringResource migration would break language choice.
package com.example.lxb_ignition.ui.i18n

import androidx.compose.runtime.Composable
import androidx.compose.runtime.staticCompositionLocalOf
import com.example.lxb_ignition.ui.copy.UserCopy

class UiI18n(private val lang: String) {
    fun tr(text: String): String {
        if (lang != "zh") return text
        return ZhMap[text] ?: text
    }

    // Batch 1: user-language version of a runtime/log message. Returns the
    // original text unchanged when UserCopy has no mapping for it.
    fun userText(text: String): String = UserCopy.runtimeMessage(text, lang) ?: text
}

val LocalUiI18n = staticCompositionLocalOf { UiI18n("en") }

@Composable
fun tr(text: String): String = LocalUiI18n.current.tr(text)

@Composable
fun ut(text: String): String = LocalUiI18n.current.userText(text)

